#!/usr/bin/env python3
"""Generate the WinUI app's design resources from the HTML prototype (~/mobile-UI, read only).

Writes into winui/GnosisVpn/:
  Ui/Tokens.g.cs   light and dark colors from src/windows/tokens.json
  Ui/Icons.g.cs    Fluent UI System Icons path data (assets/fluent, MIT), 20x20, regular/filled
  Assets/          logo-light.svg, logo-dark.svg, flags/<id>.<ext>, gvis-light.svg, gvis-dark.svg, qr.svg,
Usage: python3 -I winui/tools/gen_assets.py [PROTOTYPE_DIR]
"""
import base64, json, os, re, sys

CHECK = "--check" in sys.argv
args = [a for a in sys.argv[1:] if a != "--check"]
PROTO = args[0] if args else os.path.expanduser("~/mobile-UI")
REAL_APP = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "GnosisVpn")
# --check: generate into a temporary folder and compare with the committed files
import tempfile, filecmp
APP = tempfile.mkdtemp(prefix="gvassets-") if CHECK else REAL_APP
ASSETS, UI = os.path.join(APP, "Assets"), os.path.join(APP, "Ui")
os.makedirs(os.path.join(ASSETS, "flags"), exist_ok=True); os.makedirs(UI, exist_ok=True)

def read(*p, mode="r"):
    with open(os.path.join(PROTO, *p), mode, **({} if "b" in mode else {"encoding": "utf-8"})) as f:
        return f.read()

def write(path, data):
    with open(path, "wb" if isinstance(data, bytes) else "w", **({} if isinstance(data, bytes) else {"encoding": "utf-8"})) as f:
        f.write(data)

def css_color(v):
    """#rgb/#rrggbb/rgba(r,g,b,a) -> (a, r, g, b) bytes."""
    v = v.strip()
    if v.startswith("#"):
        h = v[1:]
        if len(h) == 3: h = "".join(c * 2 for c in h)
        return (255, int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
    m = re.fullmatch(r"rgba?\(([^)]*)\)", v)
    if m:
        p = [x.strip() for x in m.group(1).split(",")]
        a = float(p[3]) if len(p) > 3 else 1.0
        return (round(a * 255), int(p[0]), int(p[1]), int(p[2]))
    raise ValueError(v)

tokens = json.loads(read("src", "windows", "tokens.json"))
lines = ["// <auto-generated> by winui/tools/gen_assets.py from the prototype's src/windows/tokens.json </auto-generated>",
         "using Windows.UI;", "namespace GnosisVpn.Ui;", "public static partial class Tokens", "{"]
for theme in ("light", "dark"):
    lines.append(f"    public static readonly System.Collections.Generic.Dictionary<string, Color> {theme.capitalize()} = new()")
    lines.append("    {")
    for k, v in tokens[theme].items():
        a, r, g, b = css_color(v)
        lines.append(f'        ["{k}"] = Color.FromArgb({a}, {r}, {g}, {b}),')
    lines.append("    };")
lines.append("}")
write(os.path.join(UI, "Tokens.g.cs"), "\n".join(lines) + "\n")

icons = {}
folder = os.path.join(PROTO, "assets", "fluent")
for name in sorted(os.listdir(folder)):
    m = re.fullmatch(r"([a-z0-9_]+)_20_(regular|filled)\.svg", name)
    if not m: continue
    paths = re.findall(r'<path d="([^"]+)"', read("assets", "fluent", name))
    if paths: icons[f"{m.group(1)}:{m.group(2)[0]}"] = " ".join(paths)
lines = ["// <auto-generated> by winui/tools/gen_assets.py: Fluent UI System Icons (MIT, @fluentui/svg-icons 1.1.340) </auto-generated>",
         "namespace GnosisVpn.Ui;", "public static partial class Icons", "{",
         "    public static readonly System.Collections.Generic.Dictionary<string, string> Paths = new()", "    {"]
lines += [f'        ["{k}"] = "{v}",' for k, v in icons.items()]
lines += ["    };", "}"]
write(os.path.join(UI, "Icons.g.cs"), "\n".join(lines) + "\n")

img = json.loads(read("assets", "images.json"))
def data_uri(u):
    head, b64 = u.split(",", 1)
    ext = {"image/svg+xml": "svg", "image/png": "png", "image/jpeg": "jpg", "image/webp": "webp"}[head[5:].split(";")[0]]
    return ext, base64.b64decode(b64)
for key, out in (("LOGO_L", "logo-light"), ("LOGO_D", "logo-dark"), ("WORDMARK", "wordmark")):
    ext, data = data_uri(img[key]); write(os.path.join(ASSETS, f"{out}.{ext}"), data)
for fid, u in img["FLAGS"].items():
    ext, data = data_uri(u); write(os.path.join(ASSETS, "flags", f"{fid}.{ext}"), data)
def static_svg(s):
    """Windows renders SVG without SMIL animation: drop <animate>, put moving dots at their path start,
    and turn rgba() colors into hex + opacity (Direct2D SVG has no rgba())."""
    def place(m):
        circle, path = m.group(1), m.group(2)
        x, y = re.match(r"M\s*([-\d.]+)[ ,]([-\d.]+)", path).groups()
        return circle.replace("<circle", f'<circle cx="{x}" cy="{y}"', 1) + "</circle>"
    s = re.sub(r'(<circle[^>]*>)\s*<animateMotion[^>]*path="([^"]+)"[^>]*/>\s*</circle>', place, s)
    s = re.sub(r"<animate[^>]*/>", "", s)
    def rgba(m):
        attr, r, g, b, a = m.groups()
        return f'{attr}="#{int(r):02x}{int(g):02x}{int(b):02x}" {attr}-opacity="{a}"'
    return re.sub(r'(fill|stroke)="rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)"', rgba, s)

gvis = read("assets", "gvis.svg")
if "xmlns=" not in gvis[:200]: gvis = gvis.replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" ', 1)
for theme in ("light", "dark"):
    t = tokens[theme]
    vars_ = {"--gt": t["sync"], "--gvl": t["sync-line"], "--gvn": t["sync-node"], "--ink": t["text"], "--mag": t["text-3"]}
    s = re.sub(r"var\((--[a-z-]+)\)", lambda m: vars_.get(m.group(1), t.get(m.group(1)[2:], "#888")), gvis)
    s = static_svg(s)
    write(os.path.join(ASSETS, f"gvis-{theme}.svg"), s)
qr = read("assets", "qr.svg")
if "xmlns=" not in qr[:200]: qr = qr.replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" ', 1)
write(os.path.join(ASSETS, "qr.svg"), qr)
print(f"tokens {len(tokens['light'])}+{len(tokens['dark'])}, icons {len(icons)}, flags {len(img['FLAGS'])}")
if CHECK:
    diff = []
    for root, _, files in os.walk(APP):
        for f in files:
            gen = os.path.join(root, f); rel = os.path.relpath(gen, APP); com = os.path.join(REAL_APP, rel)
            if not os.path.exists(com) or not filecmp.cmp(gen, com, shallow=False): diff.append(rel)
    print("generated files match the committed ones" if not diff else "out of date: " + ", ".join(sorted(diff)))
    sys.exit(1 if diff else 0)
